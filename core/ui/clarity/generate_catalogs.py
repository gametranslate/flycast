"""Merge authored translations and build the search index; no build-time Python."""
import json, re, ast
from pathlib import Path
root=Path(__file__).resolve().parent
rows=json.loads((root/"strings.json").read_text(encoding="utf-8"))
# English aliases make shared upstream dialogs use the same translations.
for values in list(rows.values()):
    rows.setdefault(values[0], values)
for line in (root/"translations.tsv").read_text(encoding="utf-8").splitlines():
    if not line or line.startswith("#"): continue
    cols=[s.replace("\\n","\n") for s in line.split("|")]
    assert len(cols)==8 and all(cols), (len(cols), cols[0])
    rows[cols[0]]=cols
(root/"strings.json").write_text(json.dumps(rows,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
# Search indexes actual labels rather than a hand-maintained subset.
entries=set()
files=[("settings_pages.cpp",None), ("controller_panel.inc","Controllers"),
       ("../settings.cpp", "Advanced"), ("../settings_general.cpp", "Achievements")]
for name, default in files:
    source=(root/name).read_text(encoding="utf-8")
    chunks=[(default,source)]
    if name == "controller_panel.inc":
        controller, devices = source.split("void devicesPage", 1)
        chunks = [("Controllers", controller), ("Devices", devices)]
    elif name == "../settings.cpp":
        source = source.split("void gui_settings_advanced()", 1)[1].split("void gui_debug_tab()", 1)[0]
        chunks = [("Advanced", source)]
    elif name == "../settings_general.cpp":
        chunks = [("Achievements", source.split("void gui_settings_achievements()", 1)[1])]
    if not default:
        chunks=[]
        fn_to_page={"generalPage":"System","graphicsPage":"Video","audioPage":"Audio","libraryPage":"Library","pathsPage":"Paths","networkPage":"Network","aboutPage":"About"}
        for match in re.finditer(r"void (\w+Page)\(\)\s*\{", source):
            if match[1] not in fn_to_page: continue
            end=source.find("\nvoid ",match.end())
            chunks.append((fn_to_page[match[1]], source[match.end():end if end!=-1 else len(source)]))
    for page, text in chunks:
        for match in re.finditer(r'(?:tr|T|choice|section|pathList|singlePath|textOption)\(\s*("(?:[^"\\]|\\.)*")',text):
            label=ast.literal_eval(match[1])
            if len(label)<70 and label and not label.startswith("##"): entries.add((page,label))
entries.update({("Devices","Crosshair"),("Devices","Per Game VMU A1"),("Advanced","CPU Mode"),("Advanced","SH4 Clock"),("Advanced","Dump Textures"),("Achievements","RetroAchievements")})
(root/"search.inc").write_text("// Generated by generate_catalogs.py\n"+"".join(
    "{Page::"+p+", "+json.dumps(s,ensure_ascii=False)+"},\n" for p,s in sorted(entries)),encoding="utf-8")
exec((root/"generate_strings.py").read_text(encoding="utf-8"))
